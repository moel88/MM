"""Original synthesized Foley, not extracted anime/game music. Deterministic and loop-safe."""
from pathlib import Path
import json,subprocess,wave,math,io,os
import numpy as np
from scipy.signal import butter,sosfilt
HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1];RES=ROOT/'src/main/resources/assets/celestialfall';OUT=RES/'sounds/cinema';OUT.mkdir(parents=True,exist_ok=True);WORK=ROOT/'build/title-cinema/audio';WORK.mkdir(parents=True,exist_ok=True)
SR=44100;rng=np.random.default_rng(37120)
def filt(n,low,high):return sosfilt(butter(3,[low,high],fs=SR,btype='band',output='sos'),rng.normal(size=n))
def save(name,x):
 x=np.asarray(x);x=np.column_stack([x,x]) if x.ndim==1 else x;x=np.clip(x,-.92,.92)
 pcm=(x*32767).astype('<i2');wav=WORK/(name+'.wav')
 buffer=io.BytesIO()
 with wave.open(buffer,'wb') as f:f.setnchannels(2);f.setsampwidth(2);f.setframerate(SR);f.writeframes(pcm.tobytes())
 with wav.open('wb') as f:f.write(buffer.getvalue());f.flush();os.fsync(f.fileno())
 encoded=subprocess.check_output(['ffmpeg','-v','error','-i',str(wav),'-c:a','libvorbis','-q:a','5','-f','ogg','pipe:1'])
 with (OUT/(name+'.ogg')).open('wb') as f:f.write(encoded);f.flush();os.fsync(f.fileno())
# Eight distinct close shoe-on-paving steps. Separate heel, sole compression,
# tiny grit contacts and toe release, with short outdoor reflections (no hall reverb).
for i in range(8):
 t=np.arange(round(SR*.36))/SR
 def env(at,attack,decay):
  dt=np.maximum(t-at,0);return (t>=at)*(1-np.exp(-dt/attack))*np.exp(-dt/decay)
 heel_at=.008+rng.uniform(-.001,.001);sole_at=.047+rng.uniform(-.005,.006)
 heel=filt(len(t),100,1500)*env(heel_at,.0018,.017)*.92
 sole=filt(len(t),65,650)*env(sole_at,.004,.036)*.95
 # Highly damped body modes add weight without a resonant synthesized "boing".
 body=np.zeros(len(t));dt=np.maximum(t-heel_at,0)
 for hz,gain in [(94,.15),(167,.07),(263,.034)]:
  body+=gain*np.sin(math.tau*(hz+rng.uniform(-5,5))*dt)*env(heel_at,.002,.014)
 pressure=filt(len(t),350,2400)*env(sole_at+.012,.007,.032)*.32
 grit=np.zeros(len(t))
 for j in range(11):
  at=sole_at+rng.uniform(-.010,.060)
  grit+=filt(len(t),1100,6200)*env(at,.0007,rng.uniform(.0014,.0042))*rng.uniform(.035,.105)
 release=filt(len(t),650,3400)*env(.13+rng.uniform(-.01,.015),.012,.025)*.16
 dry=heel+sole+body+pressure+grit+release
 dry*=np.minimum(1,np.maximum(.33-t,0)/.025)
 # Modest equal-power placement alternates shoes; the sound remains close and centred.
 peak=max(abs(dry));dry*=.64/max(peak,.001)
 pan=(-1 if i%2==0 else 1)*.10;left=dry*math.sqrt((1-pan)/2);right=dry*math.sqrt((1+pan)/2)
 for delay,gain in [(18,.065),(39,.031),(67,.014)]:
  n=round(SR*delay/1000);left[n:]+=dry[:-n]*gain;right[n+13:]+=dry[:-(n+13)]*gain*.82
 save('step_'+str(i+1),np.column_stack([left,right]))
t=np.arange(round(SR*.8))/SR;x=filt(len(t),250,4500)*np.sin(math.pi*t/.8)**2*.14;save('cloth',x)
t=np.arange(round(SR*2.4))/SR;x=np.zeros(len(t))
for f,g in [(1046.5,.15),(1568,.066),(2093,.05),(2637,.03),(3136,.014)]:x+=g*np.sin(math.tau*f*t)*np.exp(-t*(1.8+f/2500))
x*=np.minimum(1,t/.014)*np.minimum(1,(2.4-t)/.22);save('chime',np.column_stack([x,np.roll(x,145)*.88]))
t=np.arange(round(SR*1.4))/SR;x=filt(len(t),1200,9800)*.15*np.sin(math.pi*t/1.4)**2;save('sand',x)
# Periodic noise spectrum: smooth wind, not loud music. This exact 12-second loop has no splice jump.
n=SR*12;freq=np.fft.rfftfreq(n,1/SR);phase=rng.uniform(0,math.tau,len(freq));spectrum=np.exp(-freq/2100)/(np.maximum(freq,90)**.52);spectrum[freq<70]=0
x=np.fft.irfft(spectrum*np.exp(1j*phase),n);x=x/np.max(abs(x))*.18;t=np.arange(n)/SR;x*=.74+.14*np.sin(math.tau*t/12)+.08*np.sin(math.tau*t/6)
# Quiet distant, original birdlike two-note tones repeat at the loop boundary.
for start in [2.0,7.0]:
 d=t-start;env=np.where((d>=0)&(d<.5),np.sin(math.pi*np.clip(d,0,.5)/.5)**2,0);x+=.013*np.sin(math.tau*(2100*d+340*d*d))*env
save('ambience',np.column_stack([x,np.roll(x,3800)*.9]))
p=RES/'sounds.json';data=json.loads(p.read_text())
for name in [*['step_'+str(i) for i in range(1,9)],'cloth','chime','sand','ambience']:
 data['cinema_'+name]={'sounds':[{'name':'celestialfall:cinema/'+name,'stream':name=='ambience','preload':name!='ambience'}]}
p.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
(OUT/'license.txt').write_text('Original procedural Foley and ambience for BOMI STAND. Generated by tools/title_cinema/build_audio.py. This notice covers only the procedural footsteps, cloth, chime, sand and ambience. The separately supplied title_satellites music is credited in music_sources.json and is not covered by this Foley notice.\n')
print('Eight distinct layered footsteps + four original Foley/ambience assets encoded')
